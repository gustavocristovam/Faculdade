//Ler 4 números, calcular o quadrado para cada um, somar todos os quadrados e mostrar o resultado


public class SomaQuadrados {
    public static void main(String[] args) {
            int n1 = 15,n2=2,n3=3,n4=12;
            int soma = n1*n1 + n2*n2 + n3*n3 + n4*n4;
            System.out.println("A soma dos quadrados dos números é: " + soma);
    }
}
